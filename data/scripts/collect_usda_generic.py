usda = {r['fdc_id']: r for r in csv.DictReader(open(SRC, encoding='utf-8-sig'))}
rows = []
for name, cat, fid, g, label, alias in MAP:
    u = usda[fid]
    per100 = float(u['caffeine_mg_per_100g'])
    rows.append({'name_ko': name, 'brand': '', 'category': cat, 'subcategory': '일반 식품',
                 'serving': label, 'caffeine_mg': round(per100 * g / 100, 1),
                 'source': f"USDA FoodData Central ({u['source']}) · {u['description']} · 100g당 {per100}mg",
                 'source_url': f'https://fdc.nal.usda.gov/food-details/{fid}/nutrients',
                 'checked_at': today, 'confidence': 'estimate_foreign_db', 'aliases': alias})

for name, fid, grain, note in GRAIN_TEAS:
    u = usda[fid]
    assert float(u['caffeine_mg_per_100g']) == 0
    rows.append({'name_ko': name, 'brand': '', 'category': '차', 'subcategory': '곡물차',
                 'serving': '1컵(240ml)', 'caffeine_mg': 0.0,
                 'source': f"원재료 기준 추정: {grain}({u['description']})의 카페인 0mg (USDA {u['source']}) · {note}",
                 'source_url': f'https://fdc.nal.usda.gov/food-details/{fid}/nutrients',
                 'checked_at': today, 'confidence': 'ingredient_based', 'aliases': ''})

with open(OUT, 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader(); w.writerows(rows)
print(len(rows), 'rows ->', OUT)
